import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const src=p=>readFileSync(new URL("../../"+p,import.meta.url),"utf8");
const actions=src("components/WalletActions.tsx");
const card=src("components/LoyaltyCard.tsx");
const style=src("app/workspace.css");
const backend=src("lib/server/wallet.ts");
assert.match(actions,/onClick=\{\(\)=>onUnavailable\(p.id\)\}/,"Unavailable Wallet choices must react to a tap");
assert.match(actions,/onUnavailable:\(provider:Provider\)=>void/);
assert.match(actions,/href=\{"\/api\/local\/wallet\/"\+p.id/,"Available Wallet providers retain real links");
assert.match(actions,/lp-wallet-disabled/);
assert.doesNotMatch(card,/WalletActions|walletNotice|unavailableWallet|\/api\/local\/wallet|wallet\/status/,"Wallet integrations must stay hidden until launch");
assert.doesNotMatch(card,/Apple Wallet|Google Wallet/,"No Wallet setup warnings in the customer card");
assert.match(card,/setOpen\(true\)/);
assert.match(card,/Guardar imagen con QR/);
assert.match(card,/onClick=\{\(\)=>setExpandedQr\("card"\)\}/);
assert.match(card,/onClick=\{\(\)=>setExpandedQr\("reward"\)\}/);
assert.match(card,/aria-modal="true"/);
assert.match(card,/qr-fullscreen-image/);
assert.match(card,/event.key==="Escape"/);
assert.match(card,/document.body.style.overflow="hidden"/);
assert.match(card,/data-card-qr=\{membership.id\}/,"PNG download keeps a discoverable QR");
assert.match(style,/\.qr-fullscreen-overlay\{position:fixed;inset:0/);
assert.match(style,/\.qr-fullscreen-image\{[\s\S]*?width:min\(88vw,66dvh,488px\)/);
assert.match(backend,/APPLE_WALLET_CERT_PEM_B64/);
assert.match(backend,/GOOGLE_WALLET_ISSUER_ID/);
console.log("OK: Wallet controls are hidden; QR download and card/reward fullscreen still work.");

assert.match(style,/\.loyalty-global-bottom-nav\{z-index:150\}/,"Find existing bottom navigation stacking order");
assert.match(style,/\.qr-modal-backdrop\{z-index:500/,"Card modal must always render over the fixed bottom navigation");
assert.match(style,/\.qr-modal\{padding-bottom:calc\(42px \+ env\(safe-area-inset-bottom,0px\)\)/,"Modal must have room to reach the last action");
assert.doesNotMatch(card,/Kreyv active la emisión de tarjetas/,"Wallet configuration notice must not appear in the UI");
console.log("OK: card modal sits above fixed navigation and its final actions stay scrollable.");
