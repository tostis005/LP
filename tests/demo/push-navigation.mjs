import assert from "node:assert/strict";
import {readFileSync} from "node:fs";

const read=path=>readFileSync(path,"utf8");
const home=read("app/app/page.tsx");
const route=read("app/app/ajustes/page.tsx");
const profile=read("app/app/perfil/page.tsx");
const frame=read("components/AppFrame.tsx");
const nav=read("components/AppBottomNav.tsx");
const widget=read("components/PushPreferences.tsx");
assert.match(read("components/LoyaltyCard.tsx"),/ajustes\?business=/,"Cada tarjeta abre directamente sus preferencias de notificaciones");
assert.doesNotMatch(profile,/href="\/app\/ajustes"/,"Mi perfil no debe mezclar ajustes ni notificaciones");
assert.match(nav,/href:"\/app\/ajustes",label:"Ajustes"/,"El menú inferior móvil debe incluir Avisos");
assert.match(frame,/href:"\/app\/ajustes",label:"Ajustes"/,"El menú de escritorio debe incluir Notificaciones");
assert.match(route,/<PushPreferences showBusinesses=\{false\}\/>/,"Ajustes incluye control real del teléfono");
assert.match(route,/<CustomerNotificationSettings account=\{account\}\/>/,"Ajustes incluye consentimientos por tarjeta");
assert.match(widget,/Notification\.requestPermission\(\)/,"Los permisos se solicitan al tocar el botón");
assert.match(widget,/action:"subscribe"/,"La pantalla debe registrar una suscripción real");
assert.match(widget,/action:"consent"/,"Cada negocio requiere consentimiento expreso");
console.log("OK: notificaciones visibles en móvil, tarjetas y perfil, con activación y consentimiento.");
