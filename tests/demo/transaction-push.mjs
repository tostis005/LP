import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {runInNewContext} from "node:vm";
import ts from "typescript";
const read=p=>readFileSync(new URL("../../"+p,import.meta.url),"utf8");
const mod={exports:{}};
runInNewContext(ts.transpileModule(read("lib/transaction-push-copy.ts"),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,{module:mod,exports:mod.exports,Intl});
const copy=mod.exports.transactionPushCopy;
const base={program_type:"stamps",currency:"MXN",amount_delta:2,balance:7,reward_cost:10,reward_label:"Café gratis"};
assert.equal(copy(base).title,"¡Has ganado 2 sellos!");
assert.equal(copy(base).body_text,"Ya tienes 7 de 10 sellos. ¡Solo te faltan 3 para conseguir tu premio!");
assert.equal(copy({...base,program_type:"points",amount_delta:50,balance:350,reward_cost:500}).body_text,"Tu nuevo saldo es de 350 puntos. Sigue acumulando recompensas.");
assert.equal(copy({...base,program_type:"cashback",amount_delta:2500,balance:12500}).body_text,"Has acumulado $25 MXN. Tu saldo disponible es de $125 MXN.");
assert.match(copy({...base,balance:10}).title,/Premio conseguido/);
assert.match(copy({...base,balance:10}).body_text,/2 sellos/);
const sql=read("db/migrations/999_zzzzzzzzzzzzzzzzzzzzzzzzzz_transaction_push.sql"),rpc=read("app/api/local/rpc/route.ts");
assert.match(sql,/ON CONFLICT\(transaction_id\) DO NOTHING/);
assert.match(sql,/s.customer_id=m.customer_id/);
assert.match(sql,/s.active AND s.transaction_opted_in/);
assert.doesNotMatch(sql,/push_usage_ledger|push_campaigns/);
assert.match(rpc,/dispatchTransactionPush\(eventId\)/);
assert.match(read("lib/server/web-push.ts"),/\/app\?card=/);
assert.match(read("components/LoyaltyCard.tsx"),/deviceToken\|\|membership.card_token/);
assert.match(read("scripts/automation-worker.mjs"),/transactionCycle/);
console.log("OK: precise credit notices, one private device, dedicated consent, no campaign billing, direct card link.");
