import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {runInNewContext} from "node:vm";
import ts from "typescript";
const read=p=>readFileSync(new URL("../../"+p,import.meta.url),"utf8");
const source=read("lib/kreyv-icon-paths.ts");
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const m={exports:{}};
runInNewContext(js,{module:m,exports:m.exports});
const icons=m.exports.KREYV_FILLED_PATHS;
assert.equal(Object.keys(icons).length,43);
for(const key of ["cafeteria","barberia","floristeria","spa","automocion","categorias"])assert.ok(icons[key],"Missing "+key);
assert.notEqual(icons.floristeria,icons.spa,"Flower shops and spa must not share an icon");
assert.notEqual(icons.cafeteria,icons.restaurante);
assert.doesNotMatch(icons.cafeteria,/M6,54L52,54/,"Cafetería must not include an off-centre saucer");
assert.ok(icons.cafeteria.length>180,"Cafetería needs a well-defined cup silhouette");
assert.ok(icons.automocion.length>130,"Automoción must have a car icon");
assert.notEqual(icons.automocion,icons.comercio);
assert.notEqual(icons.categorias,icons.libreria);
assert.ok(icons.barberia.length>180,"Barbería must have a full beard and distinct moustache");
const cats=read("lib/business-categories.ts");
assert.match(cats,/name:"Floristería",stamp:"floristeria"/);
assert.match(cats,/name:"Spa y bienestar",stamp:"spa"/);
const stamp=read("lib/stamp-drawings.ts");
assert.match(stamp,/"flower": "floristeria"/,"Saved flower icons still work");
assert.match(stamp,/id:"floristeria",label:"Floristería"/);
const home=read("components/LandingHome.tsx");
for(const name of ["cafeteria","barberia","floristeria","spa"])assert.match(home,new RegExp('kind="'+name+'"'));
assert.doesNotMatch(home,/kind="flower"/);
assert.match(home,/kind="automocion"/);
assert.match(home,/kind="categorias"/);
assert.match(home,/\["cafeteria","hamburgueseria","restaurante","barberia"/);
const install=read("components/InstallGuide.tsx");
assert.match(install,/<img src="\/icon.svg" alt=""/);
assert.match(install,/KreyvIcon name="cafeteria"/);
assert.doesNotMatch(install,/>L<\/span>/,"No Loyally placeholder in phone mockup");
const css=read("app/landing.css");
for(const token of ["--color-bg","--color-accent-100","--color-brand-900","--color-brand-100"])assert.ok(css.includes("var("+token+")"));
assert.match(css,/\.loi-site \.loi-process\{background:var\(--color-brand-900\)/,"Dark process section");
assert.match(css,/\.loi-site \.loi-section\{background:#fff\}/,"White benefits section");
assert.match(css,/\.loi-site \.loi-install-section\{[\s\S]*?var\(--color-accent-100\)/,"Warm yellow install section");
assert.match(css,/\.loi-site \.loi-audience-expanded \.loi-audience-list>span>\.kreyv-icon/,"Uniform category icon scale");
assert.match(css,/\.loi-site \.loi-stamp-library>div\{display:grid;grid-template-columns:repeat\(6/,"Gallery fits in the preview");
assert.match(css,/grid-template-columns:30px minmax\(0,1fr\)/,"Category icons have a stable centering column");
assert.match(css,/justify-self:center;align-self:center/,"Icons are centered both ways");
assert.match(css,/@media\(max-width:580px\)/,"Responsive details remain");
assert.match(read("db/migrations/270_floristeria_distinct_icon.sql"),/'floristeria'/);
console.log("OK: professional 43-icon family, consistent home grid and responsive Kreyv palette.");
