import assert from "node:assert/strict";
import pg from "pg";

const pool=new pg.Pool({
 host:process.env.PGHOST||"127.0.0.1",port:Number(process.env.PGPORT||5432),
 database:process.env.POSTGRES_DB,user:process.env.POSTGRES_USER,password:process.env.POSTGRES_PASSWORD
});
const client=await pool.connect();
try{
 const user=await client.query("SELECT id,email FROM auth.users WHERE lower(email)='cliente@loyally.local'");
 assert.equal(user.rowCount,1,"The real QA customer must exist");
 const customerId=user.rows[0].id;

 await client.query("BEGIN");
 const hidden=(await client.query(
  "INSERT INTO public.businesses(name,slug,public_listing,active) VALUES('Privado QA','ci-private-customer-visibility',false,true) RETURNING id"
 )).rows[0].id;
 await client.query("SET LOCAL ROLE authenticated");
 await client.query("SELECT set_config('request.jwt.claim.sub',$1,true),set_config('request.jwt.claim.email',$2,true)",
  [customerId,user.rows[0].email]);

 // This is the same SQL generated by the native data API for the customer card list.
 const cards=await client.query(`
  SELECT t.*,
   (SELECT row_to_json(r) FROM
    (SELECT b.* FROM public.businesses b WHERE b.id=t.business_id LIMIT 1) r
   ) AS businesses
  FROM public.loyalty_memberships t
  WHERE t.customer_id=$1
  ORDER BY t.created_at DESC LIMIT 250
 `,[customerId]);
 assert.equal(cards.rowCount,4,"The QA customer must see four real memberships");
 for(const card of cards.rows){
  assert.ok(card.businesses&&typeof card.businesses.name==="string",
   "The customer must be able to see the name of every enrolled merchant");
  assert.ok(card.businesses.id===card.business_id,"The merchant must match the membership");
  assert.match(card.card_token,/^[0-9a-f-]{36}$/i,"The card must have a valid QR token");
 }
 const unrelated=await client.query("SELECT id FROM public.businesses WHERE id=$1",[hidden]);
 assert.equal(unrelated.rowCount,0,"A customer must NOT see another private business without a membership");
 const ids=cards.rows.map(r=>r.business_id),membershipIds=cards.rows.map(r=>r.id);
 const programs=await client.query("SELECT * FROM public.loyalty_programs t WHERE t.business_id=ANY($1::uuid[])",
  [ids]);
 assert.equal(programs.rowCount,4,"The customer must be able to read every joined program");
 const movements=await client.query(
  "SELECT id,amount_delta,kind,created_at,business_id FROM public.loyalty_transactions t WHERE t.membership_id=ANY($1::uuid[]) ORDER BY t.created_at DESC LIMIT 10",
  [membershipIds]);
 assert.ok(Array.isArray(movements.rows),"The activity query must work for a real customer");
 await client.query("ROLLBACK");
 console.log("OK: client access to four live QR cards, merchant details, programs and recent activity.");
}catch(e){await client.query("ROLLBACK").catch(()=>{});throw e}
finally{client.release();await pool.end()}
